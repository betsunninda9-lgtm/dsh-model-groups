import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build as bundle } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const withoutExports = source => source.replace(/^export /gm, '');
const clientSource = name => withoutExports(read(name)).replace(/^import .*;\n/gm, '');
// Styles belong to the mounted plugin, not to module materialization: a
// disposal removes them and a re-applied (memoized) module must restore them.
const styles = `\nconst MODEL_GROUPS_CSS = ${JSON.stringify(read('src/groups.css') + '\n' + read('src/bridge/provider-card.css'))};\nfunction installModelGroupsStyles() {\n  const tagId = 'dsh-model-groups/groups.css';\n  if (document.querySelector('style[data-plugin-css="' + tagId + '"]') !== null) return;\n  const style = document.createElement('style');\n  style.dataset.plugin = 'dsh-model-groups';\n  style.dataset.pluginCss = tagId;\n  style.textContent = MODEL_GROUPS_CSS;\n  document.head.appendChild(style);\n}\n`;

// Tests use the very same composition as the shipped classic-script bundle,
// without writing build output or starting the application.
export function createClientSource() {
  const source = `// Generated by scripts/build.mjs; edit src instead.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-model-groups',\n  factory(require) {\n    const react = require('react');\n    const react_dom = require('react-dom');\n    const react_jsx_runtime = require('react/jsx-runtime');\n    const _deepseek_ai_dsh_client_ui_primitives = require('@deepseek-ai/dsh-client-ui-primitives');\n${clientSource('src/group-state.js')}\n${clientSource('src/hierarchy.js')}\n${read('src/model-select.js')}\n${clientSource('src/fallback.js')}\n${styles}\n${clientSource('src/capability-defaults.js')}\n${clientSource('src/bridge/store.js')}\n${clientSource('src/bridge/providers-form.js')}\n${clientSource('src/bridge/editor-state.js')}
${clientSource('src/bridge/legacy-primitives.js')}\n${clientSource('src/bridge/legacy-reorder.js')}\n${clientSource('src/bridge/legacy-models-ui.js')}\n${clientSource('src/bridge/provider-card.js')}\n${clientSource('src/client.js')}\n    return { apply, inject };\n  },\n});\n`;
  // Compile the classic-script bundle before returning or writing anything.
  new Function(source);
  return source;
}

export async function createServerSource() {
  const version = JSON.parse(read('package.json')).version;
  const result = await bundle({
    absWorkingDir: root, entryPoints: ['src/bridge/host.js'], bundle: true,
    platform: 'node', format: 'esm', target: 'node22', packages: 'external',
    write: false, legalComments: 'none',
    banner: { js: `// Generated public-service backend for dsh-model-groups ${version}.` },
  });
  return result.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const version = JSON.parse(read('package.json')).version;
  const outputs = [['lib/client.js', createClientSource()], [`lib/bridge-host-${version}.js`, await createServerSource()]];
  for (const [name, source] of outputs) {
    const target = path.join(root, name);
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) throw new Error(`${name} is stale. Run npm run build.`);
      console.log(`${name} is up to date.`);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, source);
      console.log(`Built ${name} (${Buffer.byteLength(source)} bytes).`);
    }
  }
}
